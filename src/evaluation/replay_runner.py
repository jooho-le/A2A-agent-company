"""Private, stdlib-only input recorder/replayer mounted beside _unit_runner.py.

The first output line is evaluator-private. Callers must remove it before
publishing reports. Inputs are generated by the protected tests, never by the
code under test. Thread scheduling and Argon2 salts are intentionally not replayed.
"""
import importlib.util
import json
import sys
import threading
from pathlib import Path


_DETAIL_RESULTS = None

def detail_results():
    return _DETAIL_RESULTS


class InputTape:
    def __init__(self, replay=None, error_type=ValueError):
        self.replay = replay
        self.tests, self.positions, self.errors = {}, {}, {}
        self.active = None
        self.lock = threading.Lock()
        self.error_type = error_type

    def begin(self, test_id):
        self.active = test_id
        self.tests.setdefault(test_id, [])
        self.positions.setdefault(test_id, 0)

    def value(self, kind, arguments, produce):
        # One test runs at a time; its concurrent identical HTTP requests share
        # this lock. The lock covers bookkeeping, never service execution.
        with self.lock:
            test_id = self.active
            if test_id is None:
                raise self.error_type('REPLAY_TEST_CONTEXT_MISSING')
            arguments = json.loads(json.dumps(arguments, allow_nan=False))
            if self.replay is None:
                value = produce()
            else:
                rows = self.replay.get(test_id, [])
                index = self.positions[test_id]
                if (index >= len(rows) or rows[index].get('kind') != kind
                        or rows[index].get('arguments') != arguments):
                    self.errors[test_id] = 'REPLAY_INPUT_MISMATCH'
                    raise self.error_type('REPLAY_INPUT_MISMATCH')
                value = rows[index]['value']
            value = json.loads(json.dumps(value, allow_nan=False))
            self.tests[test_id].append({'kind': kind, 'arguments': arguments, 'value': value})
            self.positions[test_id] += 1
            return value

    def payload(self, report):
        outcomes = {row['testId']: row['outcome'] for row in (report or {}).get('tests', [])}
        # dev unittest-v1 calls its rows "cases" in older schema versions.
        if not outcomes:
            outcomes = {row['testId']: row['outcome'] for row in (report or {}).get('cases', [])}
        rows = {}
        for test_id in sorted(set(self.tests) | set(self.replay or {})):
            consumed = self.positions.get(test_id, 0)
            total = len((self.replay if self.replay is not None else self.tests).get(test_id, []))
            complete = test_id in self.tests and consumed == total
            # A known assertion failure can stop the test after a matched input
            # prefix. This is recorded explicitly, never called a full replay.
            prefix_failure = (not complete and test_id in self.tests and consumed > 0
                              and outcomes.get(test_id) == 'FAIL')
            rows[test_id] = {'consumed': consumed, 'total': total, 'complete': complete,
                             'matchedFailurePrefix': prefix_failure,
                             'error': self.errors.get(test_id)}
        valid = (bool(rows) and not self.errors and report is not None
                 and set(rows) == set(outcomes)
                 and all(row['complete'] or row['matchedFailurePrefix'] for row in rows.values()))
        status = ('RECORDED' if self.replay is None else
                  'PASS' if all(row['complete'] for row in rows.values()) else 'MATCHED_FAILURE_PREFIX') if valid else 'UNVERIFIED'
        return {'schemaVersion': 1, 'status': status, 'tests': self.tests, 'checks': rows}


def _load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module
    spec.loader.exec_module(module)
    return module


def run_tests_with_inputs(test_root, source_root, pattern):
    global _DETAIL_RESULTS
    _DETAIL_RESULTS = None
    root = Path(__file__).resolve().parent
    runner = _load('trusted_unit_runner', root / '_unit_runner.py')
    details = _load('signup_details', Path(test_root) / 'signup_details.py')
    details.COLLECTED.clear()
    link = _load('signup_link', Path(test_root) / 'signup_link.py')
    request = json.loads((root / '_input_replay.json').read_text(encoding='utf-8'))
    tape = InputTape(request.get('tests'), link.Unverified)
    link._TAPE = tape
    try:
        report, code = runner.run_tests(test_root, source_root, pattern)
    finally:
        link._TAPE = None
        _DETAIL_RESULTS = details.payload()
    return report, code, tape.payload(report)


def main(argv=None):
    import argparse
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument('--kind', choices=('PROTECTED',), required=True)
    parser.add_argument('--directory', required=True)
    parser.add_argument('--pattern', required=True)
    tape = None
    try:
        args = parser.parse_args(argv)
        runner = _load('trusted_unit_runner_outer', Path(__file__).with_name('_unit_runner.py'))
        if not runner._safe_directory(args.directory) or runner._SAFE_PATTERN.fullmatch(args.pattern) is None:
            raise ValueError('TEST_RUNNER_ERROR')
        with runner._discard_file_descriptors():
            report, code, tape = run_tests_with_inputs(Path('/inputs') / args.directory, Path('/snapshot'), args.pattern)
    except BaseException:
        report, code = None, 2
    sys.stdout.write(json.dumps({'protected-details-v1': detail_results()}, separators=(',', ':'), allow_nan=False) + '\n')
    sys.stdout.write(json.dumps({'protected-inputs-v1': tape}, separators=(',', ':'), allow_nan=False) + '\n')
    sys.stdout.write(json.dumps(report if report is not None else {'error': 'TEST_RUNNER_ERROR'},
                               separators=(',', ':'), allow_nan=False) + '\n')
    sys.stdout.flush()
    return code


if __name__ == '__main__':
    raise SystemExit(main())
